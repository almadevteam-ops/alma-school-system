CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  display_name VARCHAR(100) NOT NULL,
  pass_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','secretary','finance') NOT NULL DEFAULT 'secretary',
  active TINYINT(1) NOT NULL DEFAULT 1,
  pw_ver INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL,
  last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL,
  ip VARCHAR(45) NOT NULL,
  ok TINYINT(1) NOT NULL,
  created_at DATETIME NOT NULL,
  INDEX (ip, created_at),
  INDEX (username, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME NOT NULL,
  user_id INT UNSIGNED NULL,
  username VARCHAR(60) NOT NULL,
  action VARCHAR(40) NOT NULL,
  entity VARCHAR(40) NOT NULL DEFAULT '',
  entity_id VARCHAR(40) NOT NULL DEFAULT '',
  detail VARCHAR(500) NOT NULL DEFAULT '',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  INDEX (created_at),
  INDEX (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS students (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  grade VARCHAR(4) NOT NULL,
  cls VARCHAR(8) NOT NULL DEFAULT '',
  idn VARCHAR(20) NOT NULL DEFAULT '',
  dob VARCHAR(12) NOT NULL DEFAULT '',
  addr VARCHAR(200) NOT NULL DEFAULT '',
  city VARCHAR(80) NOT NULL DEFAULT '',
  email VARCHAR(150) NOT NULL DEFAULT '',
  phone VARCHAR(30) NOT NULL DEFAULT '',
  f_name VARCHAR(80) NOT NULL DEFAULT '',
  f_phone VARCHAR(30) NOT NULL DEFAULT '',
  f_id VARCHAR(20) NOT NULL DEFAULT '',
  m_name VARCHAR(80) NOT NULL DEFAULT '',
  m_phone VARCHAR(30) NOT NULL DEFAULT '',
  m_id VARCHAR(20) NOT NULL DEFAULT '',
  hmo VARCHAR(30) NOT NULL DEFAULT '',
  marital VARCHAR(12) NOT NULL DEFAULT 'married',
  status ENUM('active','left','pending') NOT NULL DEFAULT 'active',
  notes TEXT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  INDEX (name),
  INDEX (grade),
  INDEX (city),
  INDEX (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
