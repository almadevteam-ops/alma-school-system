CREATE TABLE IF NOT EXISTS payers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  notes VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS families (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  monthly DECIMAL(10,2) NOT NULL DEFAULT 0,
  months TINYINT UNSIGNED NOT NULL DEFAULT 10,
  method VARCHAR(20) NOT NULL DEFAULT '',
  collect_day TINYINT UNSIGNED NULL,
  payer_id INT UNSIGNED NULL,
  discount_note VARCHAR(255) NOT NULL DEFAULT '',
  notes TEXT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  INDEX (name),
  INDEX (payer_id),
  CONSTRAINT fk_fam_payer FOREIGN KEY (payer_id) REFERENCES payers(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
ALTER TABLE students ADD COLUMN family_id INT UNSIGNED NULL, ADD INDEX (family_id), ADD CONSTRAINT fk_st_family FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE SET NULL;
CREATE TABLE IF NOT EXISTS charges (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  family_id INT UNSIGNED NOT NULL,
  kind VARCHAR(20) NOT NULL DEFAULT 'other',
  label VARCHAR(100) NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  created_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL,
  voided_at DATETIME NULL,
  INDEX (family_id),
  CONSTRAINT fk_ch_family FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payments (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  family_id INT UNSIGNED NOT NULL,
  charge_id INT UNSIGNED NULL,
  for_month TINYINT UNSIGNED NULL,
  amount DECIMAL(10,2) NOT NULL,
  paid_on DATE NOT NULL,
  method VARCHAR(20) NOT NULL DEFAULT 'other',
  ref VARCHAR(60) NOT NULL DEFAULT '',
  note VARCHAR(255) NOT NULL DEFAULT '',
  payer_id INT UNSIGNED NULL,
  batch VARCHAR(32) NOT NULL DEFAULT '',
  created_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL,
  voided_at DATETIME NULL,
  voided_by INT UNSIGNED NULL,
  INDEX (family_id),
  INDEX (batch),
  INDEX (payer_id),
  CONSTRAINT fk_pay_family FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
